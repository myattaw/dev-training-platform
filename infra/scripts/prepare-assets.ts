/**
 * Stages build output for the CDK app (infra/.build):
 *
 *   web-immutable/   content-hashed files (cached for a year)
 *   web-revalidate/  everything else: index.html, content/, … (revalidated)
 *   lambda/          the bundled API function
 *
 * Run by `npm run deploy:prepare` after the web and Lambda builds. Refuses
 * output that contains private content.
 */
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../..');
export const BUILD_DIR = resolve(here, '../.build');

/** Files whose names contain a content hash (Angular's output naming). */
export function isImmutableAsset(path: string): boolean {
  const p = path.split(sep).join('/');
  return (
    /^(chunk|main|polyfills|styles|worker)-[A-Z0-9]{8}\.(js|css)(\.map)?$/.test(p) ||
    /^media\/[^/]+-[A-Z0-9]{8}\.[a-z0-9]+$/.test(p)
  );
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

export function prepareAssets(
  web = join(repoRoot, 'dist', 'web', 'browser'),
  lambdaDir = join(repoRoot, 'services', 'api', 'dist', 'lambda'),
  out = BUILD_DIR,
): void {
  if (!existsSync(join(web, 'index.html')))
    throw new Error(`No web build in ${web}. Run "npm run build" first.`);
  if (!existsSync(join(lambdaDir, 'index.mjs')))
    throw new Error(
      `No Lambda bundle in ${lambdaDir}. Run "npm run build:lambda -w @pracstack/api".`,
    );
  if (existsSync(join(web, 'content', 'private')))
    throw new Error('The web build contains private content; refusing to stage it.');

  rmSync(out, { recursive: true, force: true });
  for (const file of listFiles(web)) {
    const rel = relative(web, file);
    // config.json is generated by the stack with the deployment's settings.
    if (rel === 'config.json') continue;
    const target = join(out, isImmutableAsset(rel) ? 'web-immutable' : 'web-revalidate', rel);
    mkdirSync(dirname(target), { recursive: true });
    cpSync(file, target);
  }
  cpSync(lambdaDir, join(out, 'lambda'), { recursive: true });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  prepareAssets();
  console.log(`Staged deployment assets in ${BUILD_DIR}`);
}
